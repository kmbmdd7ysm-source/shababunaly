export function compareBrands(a: string, b: string): number {
  const ai = BRAND_PRIORITY.indexOf(a);
  const bi = BRAND_PRIORITY.indexOf(b);
  if (ai === -1 && bi === -1) return a.localeCompare(b);
  if (ai === -1) return 1;
  if (bi === -1) return -1;
  return ai - bi;
}
