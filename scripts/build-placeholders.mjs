/*
 * Concept-plate generator.
 *
 * The catalogue placeholders were crude Arial line drawings on a hard black
 * rectangle, captioned with a stacked "SHABABUNA / <CATEGORY> / SHABABUNA ·
 * BUILT DIFFERENT" lockup. Three problems:
 *
 *   1. They read as a fake printed product label rather than as a stand-in, and
 *      the repeated wordmark looked like branding applied to a real garment.
 *   2. The opaque black rectangle fought every ground they were placed on — on
 *      the product stage it showed as a hard-edged panel with bright seams.
 *   3. They used Arial, so they were the only type on the site not in the
 *      brand's own faces.
 *
 * These plates are transparent, use the site's display family with a sane
 * fallback chain, and say exactly one honest thing: this is concept artwork and
 * the photography is pending. The silhouette is drawn from the same court
 * vocabulary as the icon set — flat, geometric, obviously a diagram.
 *
 * Run: node scripts/build-placeholders.mjs
 */
