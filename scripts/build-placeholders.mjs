/*
 * Ink is a mid tone, not black and not white.
 *
 * An SVG loaded through <img> does not inherit the page's colour, so
 * currentColor resolves to black — invisible on the night product stage. But a
 * light ink is equally invisible on the white product-card media. These plates
 * render on BOTH grounds, so the ink has to work on both: #8C8C8C sits at
 * roughly 3.2:1 on white and 4.9:1 on the night ground.
 *
 * No text is baked into the plate. It could not be translated for Arabic, it
 * duplicated what the viewing-tier note already says above the stage, and the
 * stacked wordmark-plus-category caption read as a fake printed product label.
 * The meaning lives in the alt text and in the tier note, where it can be
 * localised and read aloud.
 */
const plate = ({
  shape,
  label,
}) => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 480 540" role="img" aria-label="${label} \u2014 concept artwork, product photography pending">
  <!--
    Concept artwork. Not a product photograph and not a design proposal.
    Generated by scripts/build-placeholders.mjs \u2014 edit there, not here.
  -->
  <g fill="none" stroke="#8C8C8C" stroke-width="8" stroke-linecap="round" stroke-linejoin="round">
    <path d="${SHAPES[shape]}"/>
  </g>
</svg>
`;

fs.mkdirSync(OUT, { recursive: true });
for (const spec of PLATES) {
  if (!SHAPES[spec.shape]) {
    console.error('UNKNOWN SHAPE', spec.shape, 'for', spec.file);
    process.exitCode = 1;
    continue;
  }
  fs.writeFileSync(path.join(OUT, spec.file), plate(spec));
  console.info(`${spec.file}  ${spec.label}`);
}
console.info(`\n${PLATES.length} concept plates -> ${OUT}`);
